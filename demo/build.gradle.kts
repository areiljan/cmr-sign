fun dedupeTypes(generated: String): String {
    val seen = mutableSetOf<String>()
    val result = StringBuilder()
    var block = StringBuilder()
    fun flush() {
        val text = block.toString().trim()
        block = StringBuilder()
        if (text.isEmpty()) return
        val name = Regex("export (?:interface|type|enum) (\\w+)").find(text)?.groupValues?.get(1) ?: return
        if (seen.add(name)) result.append(if (result.isEmpty()) "" else "\n").append(text).append('\n')
    }
    generated.lineSequence().forEach {
        if (it.startsWith("// class ")) flush()
        block.append(it).append('\n')
    }
    flush()
    return result.toString()
}

